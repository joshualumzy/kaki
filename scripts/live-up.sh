#!/usr/bin/env bash
# Starts everything for the live run in the background, so you need one terminal, not three.
#   npm start                      install missing dependencies, check prerequisites, start the Docker stack,
#                                  the Kaki server + web, and the AI attendees, then run the preflight
#   npm stop                       stop the Kaki server, web and AI attendees (add -- --stack to stop Docker too)
# Logs go to .live-logs/dev.log and .live-logs/npc.log:  tail -f .live-logs/npc.log
cd "$(dirname "$0")/.." || exit 1
# shellcheck source=scripts/live-checks.sh
. scripts/live-checks.sh

example=.env.example

if [ ! -f "$example" ]; then
  echo "FAIL  $example is missing. Restore it from git, then run  npm start  again."
  exit 1
fi
if [ -z "$(required_keys "$example")" ]; then
  echo "FAIL  $example has no '# required:' line. Add one naming the keys a fresh clone must fill in."
  exit 1
fi
if [ ! -f .env ]; then
  echo "FAIL  .env is missing. Create it with:  cp $example .env"
  echo "      Fill in the required keys, then run  npm start  again."
  exit 1
fi
missing=$(missing_required_keys .env "$example")
if [ -n "$missing" ]; then
  echo "FAIL  .env is missing or empty for these required keys:"
  printf '      - %s\n' $missing
  echo "      Fill them in .env (see $example), then run  npm start  again."
  exit 1
fi
if ! command -v docker >/dev/null 2>&1; then
  echo "FAIL  Docker is not installed. Install Docker Desktop (https://www.docker.com/products/docker-desktop/), then run  npm start  again."
  exit 1
fi
if ! docker info >/dev/null 2>&1; then
  echo "FAIL  Docker is not running. Start Docker Desktop (or the Docker daemon), then run  npm start  again."
  exit 1
fi
if [ ! -d node_modules ]; then
  echo "node_modules is missing; installing dependencies with  npm ci ..."
  npm ci || { echo "FAIL  npm ci failed. Fix the error above, then run  npm start  again."; exit 1; }
fi

mkdir -p .live-logs
pids=.live-logs/pids

running=0
if [ -s "$pids" ]; then
  while read -r pid; do
    [ -n "$pid" ] || continue
    if ps -p "$pid" >/dev/null 2>&1; then running=1; break; fi
  done < "$pids"
fi
if [ "$running" = 1 ]; then
  echo "Already running (see $pids). Run  npm stop  first to restart."
  exit 1
fi
: > "$pids"

echo "Starting the Docker stack (Gitea, Mattermost, LiveKit, Mailpit...)"
npm run stack:up >.live-logs/stack.log 2>&1 || { echo "stack:up failed; see .live-logs/stack.log"; exit 1; }

echo "Seeding Kopitiam data (Wiki, Gitea, Mattermost, Mailpit, Calendar, Postgres)..."
npm run seed >>.live-logs/stack.log 2>&1 || { echo "seed failed; see .live-logs/stack.log"; exit 1; }

# `npm run seed` generates the Gitea and Mattermost tokens in docker/.env. Give them (and the other
# integration settings) to Kaki when the root .env leaves them unset, so a fresh clone needs no manual
# copying. Values already in the shell or the root .env win.
wire_generated_env .env docker/.env
if [ "${#WIRED_KEYS[@]}" -gt 0 ]; then
  echo "Wired from docker/.env (generated by seed): ${WIRED_KEYS[*]}"
fi

echo "Indexing company knowledge into pgvector..."
npm run index:knowledge >>.live-logs/stack.log 2>&1 || { echo "index:knowledge failed; see .live-logs/stack.log"; exit 1; }

start() { # name command...
  local name="$1"; shift
  # Job control (set -m) gives the process its own process group, so live-down.sh can stop it and its children.
  # (setsid does not exist on macOS.)
  local pid
  pid=$(set -m; nohup "$@" >".live-logs/$name.log" 2>&1 </dev/null & echo $!)
  echo "$pid" >> "$pids"
  echo "Started $name (pid $pid, log .live-logs/$name.log)"
}

start_respawn() { # name command...
  local name="$1"; shift
  local pid
  # A single crash is restarted, but a crash loop is not: after SUPERVISOR_MAX_RESTARTS (default 5)
  # exits within SUPERVISOR_WINDOW_SECONDS (default 60), the supervisor gives up loudly instead of
  # restarting forever and pretending the AI is still running.
  pid=$(set -m; nohup bash -c '
    max_restarts=${SUPERVISOR_MAX_RESTARTS:-5}
    window_seconds=${SUPERVISOR_WINDOW_SECONDS:-60}
    restarts=0
    window_start=$(date +%s)
    while true; do
      "$@"
      code=$?
      now=$(date +%s)
      if [ $((now - window_start)) -gt "$window_seconds" ]; then
        restarts=0
        window_start=$now
      fi
      restarts=$((restarts + 1))
      if [ "$restarts" -ge "$max_restarts" ]; then
        echo "[supervisor] $1 exited ($code) $restarts time(s) within ${window_seconds}s; giving up and NOT restarting" >&2
        exit 1
      fi
      echo "[supervisor] $1 exited ($code); restarting in 2s (restart $restarts of $max_restarts within ${window_seconds}s)..."
      sleep 2
    done
  ' _ "$@" >".live-logs/$name.log" 2>&1 </dev/null & echo $!)
  echo "$pid" >> "$pids"
  echo "Started $name with auto-respawn (pid $pid, log .live-logs/$name.log)"
}

start dev npm run dev
echo -n "Waiting for the web app"
web_ready=0
for _ in $(seq 1 60); do
  if curl -fsS -m 2 -o /dev/null http://localhost:5173/ 2>/dev/null; then web_ready=1; break; fi
  echo -n "."; sleep 1
done
echo
if [ "$web_ready" != 1 ]; then
  echo "FAIL  The web app did not answer on http://localhost:5173 within 60 s."
  echo "      See .live-logs/dev.log. Run  npm stop  to stop what was started."
  exit 1
fi

start_respawn npc npm run npc
echo "Giving the AI attendees a few seconds to join..."; sleep 8
if ! pgrep -f "src/npc/main" >/dev/null 2>&1; then
  echo "FAIL  The AI attendees are not running; the demo cannot open without them."
  echo "      See .live-logs/npc.log. Run  npm stop  to stop what was started."
  exit 1
fi

if ! bash scripts/live-preflight.sh; then
  echo
  echo "FAIL  The live preflight did not pass, so the demo is not ready. Fix the FAIL lines above."
  echo "      Logs: .live-logs/dev.log and .live-logs/npc.log. Run  npm stop  to stop what was started."
  exit 1
fi
echo
echo "Open http://localhost:5173 (or http://localhost:5173/practice). Watch the AI:  tail -f .live-logs/npc.log"
