type EnvKey = keyof typeof RAW_DEFAULTS;
/** The seed environment: every stack setting with its defaults and any file or process override. */
export type Env = Record<EnvKey, string>;

const ENV_KEYS = Object.keys(RAW_DEFAULTS) as EnvKey[];

/** Reads KEY=VALUE lines from a .env file, skipping blanks and comments and stripping quotes. */
export function parseEnvFile(text: string): Record<string, string> {
  const values: Record<string, string> = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator === -1) continue;
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if (
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'")))
    ) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

/** Writes the environment with the known keys in order and a generated-file header. */
export function serializeEnv(values: Record<string, string>): string {
  const lines = [
    '# Generated by npm run seed. Dev-only credentials; never commit this file.',
    '# See docker/.env.example for what each variable means.',
    '',
  ];
  for (const key of ENV_KEYS) {
    lines.push(`${key}=${values[key] ?? ''}`);
  }
  return `${lines.join('\n')}\n`;
}

function postgresUrl(env: Env): string {
  const user = encodeURIComponent(env.POSTGRES_USER);
  const password = encodeURIComponent(env.POSTGRES_PASSWORD);
  return `postgres://${user}:${password}@${env.POSTGRES_HOST}:${env.POSTGRES_PORT}/${env.POSTGRES_DB}`;
}

/** Builds the seed environment from defaults, then docker/.env, then non-empty process overrides. */
export function loadEnv(overrides: NodeJS.ProcessEnv = process.env): Env {
  const fromFile = existsSync(ENV_FILE) ? parseEnvFile(readFileSync(ENV_FILE, 'utf8')) : {};
  const values = { ...RAW_DEFAULTS } as Record<EnvKey, string>;

  for (const key of ENV_KEYS) {
    if (fromFile[key] !== undefined) values[key] = fromFile[key];
  }
  for (const key of ENV_KEYS) {
    const override = overrides[key];
    if (override !== undefined && override !== '') values[key] = override;
  }

  values.POSTGRES_URL = postgresUrl(values);
  return values;
}

/** Persists the environment to docker/.env so later commands reuse the seeded tokens. */
export function saveEnv(env: Env): void {
  writeFileSync(ENV_FILE, serializeEnv(env), 'utf8');
}
